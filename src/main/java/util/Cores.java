package util;

public class Cores {
    // Reset
    public static final String RESET = "\u001B[0m";

    // Cores do texto padrão
    public static final String VERMELHO = "\u001B[31m";
    public static final String VERDE = "\u001B[32m";
    public static final String AMARELO = "\u001B[33m";
    public static final String AZUL = "\u001B[34m";
    public static final String ROXO = "\u001B[95m"; // <-- Magenta Brilhante (Roxo)
    public static final String CIANO = "\u001B[36m";

    // Cores Estendidas (256 cores)
    public static final String LARANJA = "\u001B[38;5;208m";

    // Estilos
    public static final String NEGRITO = "\u001B[1m";
    public static final String SUBLINHADO = "\u001B[4m";
}